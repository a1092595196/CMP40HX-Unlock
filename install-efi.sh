#!/bin/sh
# install-efi.sh — NVPermissiveEFI (CMP40HX UEFI 解锁) 安装脚本
#
# 做三件事:
#   1) 把 3 个 .efi 拷到 ESP: /boot/efi/EFI/UNLOCK/
#   2) 生成 /etc/grub.d/40-cmp40hx —— 两个新 menuentry,
#      在启动 PVE 内核之前先 exec NVPermissiveEFI (compute / full 两档)
#   3) update-grub 并校验
#
# 回滚: sh uninstall-efi.sh   (或手动: rm /etc/grub.d/40-cmp40hx && update-grub
#        && rm -r /boot/efi/EFI/UNLOCK)
set -e
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ESP=${ESP:-/boot/efi}
GC=${GC:-/boot/grub/grub.cfg}
F=${F:-/etc/grub.d/40-cmp40hx}

# ---------- 前置检查 ----------
if [ -z "$SKIP_EFI_CHECK" ]; then
    [ -d /sys/firmware/efi ] || { echo "错误: 本机不是 UEFI 启动, EFI 方案不适用"; exit 1; }
fi
[ -d "$ESP" ] || { echo "错误: ESP 不在 $ESP, 运行时用 ESP=<挂载点> $0 覆盖"; exit 1; }
[ -f "$GC" ] || { echo "错误: 找不到 $GC, 运行时用 GC=<路径> $0 覆盖"; exit 1; }
[ -f "$DIR/NVPermissiveEFI-COMPUTE.efi" ] || { echo "错误: 找不到 NVPermissiveEFI-COMPUTE.efi, 先 make"; exit 1; }

if command -v mokutil >/dev/null 2>&1; then
    SB=$(mokutil --sb-state 2>/dev/null || true)
    echo "Secure Boot: $SB"
    case "$SB" in
        *"SecureBoot enabled"*)
            echo "错误: Secure Boot 开启会拒绝未签名的 .efi。先断电进 BIOS 关闭 Secure Boot 再运行本脚本。"
            exit 1 ;;
    esac
fi

# ---------- 1) ESP ----------
mkdir -p "$ESP/EFI/UNLOCK"
for f in NVPermissiveEFI.efi NVPermissiveEFI-COMPUTE.efi NVPermissiveEFI-FULL.efi; do
    [ -f "$DIR/$f" ] && install -m 0755 "$DIR/$f" "$ESP/EFI/UNLOCK/$f"
done
echo "[1/3] ESP 安装完成: $ESP/EFI/UNLOCK/ -> $(ls "$ESP/EFI/UNLOCK/" | tr '\n' ' ')"

# ---------- 2) GRUB menuentry ----------
PVE_BLOCK=$(awk '/^menuentry.*Proxmox/{f=1} f{print} f&&/^\}/{exit}' "$GC")
[ -n "$PVE_BLOCK" ] || { echo "错误: 在 $GC 中找不到 Proxmox menuentry, 无法生成引导项"; exit 1; }
# PVE 原条目去掉第一行 menuentry 头, 剩余部分(含结尾 })作为新条目主体
PVE_BODY=$(printf '%s\n' "$PVE_BLOCK" | sed '1d')

[ -f "$F" ] && cp -p "$F" "$F.bak"

{
    echo '#!/bin/sh'
    echo '# Auto-generated by install-efi.sh — NVPermissiveEFI CMP40HX UEFI unlock'
    echo "cat <<'EOF'"
    for M in COMPUTE FULL; do
        case $M in
            COMPUTE) TITLE="PVE + CMP40HX UNLOCK (compute, 最小解锁: 全套寄存器 + 1 次 SBR)" ;;
            FULL)    TITLE="PVE + CMP40HX UNLOCK (full, 对齐 Windows 完整解锁, 3 次 SBR)" ;;
        esac
        echo "menuentry \"$TITLE\" {"
        echo '    if search --no-floppy --set=unlockroot --file /EFI/UNLOCK/NVPermissiveEFI-'$M'.efi; then'
        echo '        set save_root=$root'
        echo '        set root=$unlockroot'
        echo '        echo "NVPermissiveEFI: '"$M"' unlock..."'
        echo '        exec /EFI/UNLOCK/NVPermissiveEFI-'$M'.efi'
        echo '        set root=$save_root'
        echo '    else'
        echo '        echo "ERROR: /EFI/UNLOCK/NVPermissiveEFI-'$M'.efi not found, normal boot"'
        echo '    fi'
        printf '%s\n' "$PVE_BODY"
        echo ''
    done
    echo 'EOF'
} > "$F"
chmod 0755 "$F"
echo "[2/3] 已生成 $F (备份: $F.bak, 如存在)"

# ---------- 3) update-grub ----------
if command -v update-grub >/dev/null 2>&1; then
    if update-grub > /tmp/update-grub.cmp40hx.log 2>&1; then
        N=$(grep -c 'CMP40HX UNLOCK' "$GC" || true)
        echo "[3/3] update-grub 完成, $GC 中含 $N 个新菜单项"
    else
        echo "错误: update-grub 失败, 详见:"
        cat /tmp/update-grub.cmp40hx.log
        exit 1
    fi
else
    echo "[3/3] 未找到 update-grub 命令 (测试环境?), 跳过重新生成 grub.cfg"
fi

echo
echo "============================ 完成 ============================"
echo "重启后 GRUB 菜单新增:"
echo "  • PVE + CMP40HX UNLOCK (compute, ...)  ← 推荐先用这个"
echo "  • PVE + CMP40HX UNLOCK (full, ...)"
echo "原来的 PVE 条目 = 不解锁(工厂状态), 随时可退回。"
echo "想默认进解锁项: echo \"GRUB_DEFAULT='PVE + CMP40HX UNLOCK (compute, 最小解锁: 全套寄存器 + 1 次 SBR)'\" >> /etc/default/grub && update-grub"
